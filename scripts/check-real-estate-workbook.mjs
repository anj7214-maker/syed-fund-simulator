import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { homedir } from "node:os";
import { join } from "node:path";
const modules = process.env.FUNDOPS_ARTIFACT_MODULES ?? join(homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules");
const bundled = createRequire(join(modules, "runtime-bridge.cjs"));
const { FileBlob, SpreadsheetFile } = await import(pathToFileURL(bundled.resolve("@oai/artifact-tool")));
const input = await FileBlob.load(process.argv[2]);
const workbook = await SpreadsheetFile.importXlsx(input);
workbook.recalculate();
console.log((await workbook.inspect({ kind: "table", sheetId: "NAV_Working", range: "A5:B15", maxChars: 4000, tableMaxRows: 15, tableMaxCols: 2 })).ndjson);
const nav = workbook.worksheets.getItem("NAV_Working");
const controls = workbook.worksheets.getItem("Control_Checks");
const before = nav.getRange("B12").values[0][0];
assert.equal(typeof before, "number");
assert.ok(Math.abs(controls.getRange("B5").values[0][0]) < .011);
const journals = workbook.worksheets.getItem("Journals");
const rate = workbook.worksheets.getItem("Entities");
const beforePnl = nav.getRange("B13").values[0][0];
rate.getRange("F9").values = [[1.2]];
workbook.recalculate();
const after = nav.getRange("B12").values[0][0];
assert.notEqual(after, before);
assert.equal(nav.getRange("B13").values[0][0], beforePnl);
assert.ok(Math.abs(controls.getRange("B5").values[0][0]) < .011);
console.log(JSON.stringify({ beforeNav: before, afterFxNav: after, pnlUnchanged: beforePnl, investorResidual: controls.getRange("B5").values[0][0], journalFormula: journals.getRange("I5").formulas[0][0] }));
console.log("PASS: workbook recalculated FX, NAV and investor capital without changing historical P&L. Source file was not modified.");
